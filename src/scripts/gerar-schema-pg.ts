/**
 * Gera src/db/schema-pg.ts: o esquema do PostgreSQL (Supabase) equivalente
 * ao resultado de todas as migrações do SQLite. Rodar sempre que uma
 * migração nova for acrescentada em schema.ts:
 *
 *   npm run build && node dist/scripts/gerar-schema-pg.js
 */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { MIGRACOES } from '../db/schema.js';

const raiz = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys = OFF');
for (const m of MIGRACOES) db.exec(m);

const SEM_IDENTIDADE = new Set(['empresa']);
const literal = (v: unknown) =>
  v === null || v === undefined ? 'NULL' : typeof v === 'number' || typeof v === 'bigint' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;

function converterTabela(nome: string, sql: string): string {
  let s = sql.replace(/^CREATE TABLE\s+"?(\w+)"?/, `CREATE TABLE ${nome}`);
  s = s.replace(/\bINTEGER PRIMARY KEY\b/, SEM_IDENTIDADE.has(nome) ? 'BIGINT PRIMARY KEY' : 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  s = s.replace(/\bINTEGER\b/g, 'BIGINT').replace(/\bREAL\b/g, 'DOUBLE PRECISION');
  s = s.replace(/\s+COLLATE NOCASE/gi, '');
  s = s.replace(/(?<![\w.])datetime\(/g, 'sl_datetime(').replace(/(?<![\w.])date\(/g, 'sl_date(');
  return s;
}

const partes: string[] = [];
const tabelas = db.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name <> '_migracoes' ORDER BY rowid").all() as { name: string; sql: string }[];

// Ordem que respeita as chaves estrangeiras
const ordem: string[] = [];
const pendentes = new Map(tabelas.map((t) => [t.name, t.sql]));
while (pendentes.size) {
  const antes = pendentes.size;
  for (const [nome, sql] of pendentes) {
    const deps = [...sql.matchAll(/REFERENCES\s+"?(\w+)"?/g)].map((m) => m[1]).filter((d) => d !== nome);
    if (deps.every((d) => !pendentes.has(d))) { ordem.push(nome); pendentes.delete(nome); }
  }
  if (pendentes.size === antes) throw new Error('Referência circular entre tabelas: ' + [...pendentes.keys()].join(', '));
}
for (const nome of ordem) partes.push(converterTabela(nome, tabelas.find((t) => t.name === nome)!.sql) + ';');

const indices = db.prepare("SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL").all() as { sql: string }[];
for (const i of indices) partes.push(i.sql.replace(/\s+COLLATE NOCASE/gi, '') + ';');
// O e-mail do usuário não diferencia maiúsculas (no SQLite era COLLATE NOCASE)
partes.push('CREATE UNIQUE INDEX IF NOT EXISTS ux_usuarios_email_minusc ON usuarios (lower(email));');

// Dados iniciais criados pelas migrações (empresa, perfis fiscais etc.)
for (const nome of ordem) {
  const linhas = db.prepare(`SELECT * FROM "${nome}"`).all() as Record<string, unknown>[];
  for (const l of linhas) {
    const cols = Object.keys(l);
    partes.push(`INSERT INTO ${nome} (${cols.join(', ')}) OVERRIDING SYSTEM VALUE VALUES (${cols.map((c) => literal(l[c])).join(', ')});`);
  }
}
// Sequências continuam depois dos ids inseridos acima
for (const nome of ordem) {
  if (SEM_IDENTIDADE.has(nome)) continue;
  const temId = (db.prepare(`SELECT 1 FROM pragma_table_info('${nome}') WHERE name = 'id' AND pk = 1`).get());
  if (temId) partes.push(`SELECT setval(pg_get_serial_sequence('${nome}', 'id'), GREATEST((SELECT MAX(id) FROM ${nome}), 1), (SELECT MAX(id) FROM ${nome}) IS NOT NULL);`);
}

const FUNCOES = `
-- Funções de data no formato do SQLite (texto 'AAAA-MM-DD HH:MM:SS', em UTC)
CREATE OR REPLACE FUNCTION sl_aplicar(t text, mods text[]) RETURNS timestamp LANGUAGE plpgsql STABLE AS $f$
DECLARE r timestamp; m text;
BEGIN
  IF t IS NULL THEN RETURN NULL; END IF;
  IF lower(trim(t)) = 'now' THEN r := (now() AT TIME ZONE 'UTC');
  ELSE
    BEGIN r := trim(t)::timestamp; EXCEPTION WHEN others THEN RETURN NULL; END;
  END IF;
  FOREACH m IN ARRAY coalesce(mods, '{}'::text[]) LOOP
    IF m IS NULL THEN RETURN NULL; END IF;
    m := lower(trim(m));
    IF m = 'start of month' THEN r := date_trunc('month', r);
    ELSIF m = 'start of year' THEN r := date_trunc('year', r);
    ELSIF m = 'start of day' THEN r := date_trunc('day', r);
    ELSIF m = 'localtime' THEN r := (r AT TIME ZONE 'UTC') AT TIME ZONE 'America/Fortaleza';
    ELSIF m = 'utc' THEN r := r;
    ELSIF m ~ '^[+-]?\\s*[0-9]+(\\.[0-9]+)?\\s+(second|minute|hour|day|month|year)s?$' THEN r := r + m::interval;
    ELSE RETURN NULL;
    END IF;
  END LOOP;
  RETURN r;
END $f$;
CREATE OR REPLACE FUNCTION sl_datetime(t text, VARIADIC mods text[] DEFAULT '{}') RETURNS text LANGUAGE sql STABLE
  AS $f$ SELECT to_char(sl_aplicar(t, mods), 'YYYY-MM-DD HH24:MI:SS') $f$;
CREATE OR REPLACE FUNCTION sl_date(t text, VARIADIC mods text[] DEFAULT '{}') RETURNS text LANGUAGE sql STABLE
  AS $f$ SELECT to_char(sl_aplicar(t, mods), 'YYYY-MM-DD') $f$;
CREATE OR REPLACE FUNCTION sl_julianday(t text, VARIADIC mods text[] DEFAULT '{}') RETURNS double precision LANGUAGE sql STABLE
  AS $f$ SELECT extract(epoch FROM sl_aplicar(t, mods))::double precision / 86400.0 + 2440587.5 $f$;
-- round(real, casas) existe no SQLite; no PostgreSQL só para numeric
CREATE OR REPLACE FUNCTION round(x double precision, casas integer) RETURNS double precision LANGUAGE sql IMMUTABLE
  AS $f$ SELECT round(x::numeric, casas)::double precision $f$;
`;

const saida = `/* Arquivo gerado por src/scripts/gerar-schema-pg.ts. Não editar à mão. */

/** Quantidade de migrações do SQLite já incluídas no esquema base do PostgreSQL. */
export const VERSAO_BASE_PG = ${MIGRACOES.length};

/** Funções que imitam as do SQLite (datetime, date, julianday, round). */
export const FUNCOES_PG = ${JSON.stringify(FUNCOES)};

/** Esquema completo + dados iniciais. */
export const ESQUEMA_PG = ${JSON.stringify(partes.join('\n'))};
`;
writeFileSync(join(raiz, 'src', 'db', 'schema-pg.ts'), saida);
console.log(`schema-pg.ts gerado: ${ordem.length} tabelas, ${indices.length} índices, base = migração ${MIGRACOES.length}.`);
